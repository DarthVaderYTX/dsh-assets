/**
 * Build the single browser artifact from the modular Client sources.
 *
 * The Harness module loader expects one factory per plugin id, so every
 * modality and task module is authored as a plain-JavaScript module file and
 * concatenated here in dependency order. Module files share the factory scope
 * (React, h, and the core helpers); they must not use import/export syntax.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = path.dirname(fileURLToPath(import.meta.url));

const MODULES = [
  'src/client/core/messages.js',
  'src/client/core/util.js',
  'src/client/core/ui.js',
  'src/client/core/annotation-api.js',
  'src/client/core/file-importer.js',
  'src/client/core/registry.js',
  'src/client/core/styles.js',
  'src/client/modalities/text/tasks/classification.js',
  'src/client/modalities/text/tasks/entity.js',
  'src/client/modalities/text/tasks/rating.js',
  'src/client/modalities/text/tasks/ranking.js',
  'src/client/modalities/text/index.js',
  'src/client/modalities/image/tasks/classification.js',
  'src/client/modalities/image/tasks/bbox.js',
  'src/client/modalities/image/index.js',
  'src/client/modalities/video/tasks/classification.js',
  'src/client/modalities/video/tasks/segments.js',
  'src/client/modalities/video/index.js',
  'src/client/tools-home.js',
  'src/client/datasets-home.js',
  'src/client/workbench-home.js',
  'src/client/workbench.js',
  'src/client/bootstrap.js',
];

const parts = [];
for (const relative of MODULES) {
  const source = await readFile(path.join(root, relative), 'utf8');
  if (/^\s*(?:import|export)\s/m.test(source)) {
    throw new Error(`${relative} uses import/export; module files are concatenated into one factory.`);
  }
  const banner = `// ── ${relative.split('/').slice(1).join('/')} ──`;
  parts.push(`${banner}\n${source.trim()}\n`);
}

const output = `/* human-intelligence browser entry — generated by build.mjs; edit src/client/** instead. */
window.__ModuleLoader__.load({
  id: 'human-intelligence',
  factory(require) {
    const React = require('react');
    const h = React.createElement;
    const { useCallback, useEffect, useMemo, useRef, useState } = React;

${parts.join('\n')}
  },
});
`;

await writeFile(path.join(root, 'client.js'), output, 'utf8');
new vm.Script(output, { filename: 'client.js' });
console.log(`Built client.js from ${MODULES.length} modules (${output.length} bytes).`);
